# Next line --> \n
a = "hello I am Deepanshu and \n i am big fan of harvey specter."
print(a)

# Tab space --> \t
b = "Hello I am \tHarvey Specter "
print(b)

# Double quotes me Double quote --> \"  \" 
c = "print \"Double\" quote"
print(c)

# Single quote --> \'  \'
a = "Hello My name is \'Jon Snow\'"
print(a)

# \''' \''' use to show triple quotes.
a = "Hello My name is \'''Jon Snow\''' "
print(a)

# Back space --> \b  \b
d = "My name is\b Mike Ross "
print(d)

# Carriage Return --> \r
e = "My\r name is louis Litt "
print(e)

# \\ --> use to show backslash.
d = "My name \ is \ Mike Ross "
print(d)