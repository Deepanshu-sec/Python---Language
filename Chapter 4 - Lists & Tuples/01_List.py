friends = ["Harvey", 8 , 0.95 , "Deepanshu", True]
# Ordered           # --> like strings, Lists are Ordered. 
print(friends[0])
print(friends[2])

# Mutable 
friends[0] = "Mike"  # --> Unlike strings, Lists are Mutable.
print(friends[0])

# Slicing            # --> like strings, Lists can be sliced. 
print(friends[0 : 3]) 